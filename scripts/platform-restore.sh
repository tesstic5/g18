#!/bin/bash
# scripts/platform-restore.sh — rebuild the platform from a single .cpb file.
#
#   ./scripts/platform-restore.sh backups/casino-platform-<stamp>.cpb
#
# What it does, in order:
#   1. decrypt  (your offline private key, or a passphrase)
#   2. verify   every part against the manifest SHA-256 — a corrupt archive stops here
#   3. report   row counts + whether the target's ENCRYPTION_KEY matches
#   4. confirm  (type RESTORE — unless --yes)
#   5. database stop api/worker → drop + recreate → pg_restore → verify counts
#   6. images   extract into the MinIO volume
#   7. finish   flush Redis, restart the app, wait for /health
#
# Options:
#   --key PATH        private key file (default: ./backup-key.txt)
#   --passphrase      prompt for the passphrase instead of using a key
#   --db-only         restore the database, leave images alone
#   --objects-only    restore images, leave the database alone
#   --yes             skip the typed confirmation (for automation)
#   --compose PATH    compose file to use
set -euo pipefail

DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$DIR"

FILE="${1:-}"
[ -n "$FILE" ] && shift || true
[ -f "$FILE" ] || { echo "usage: $0 <backup.cpb> [options]   (file not found: ${FILE:-none})" >&2; exit 2; }

PG_SVC="${PG_SVC:-postgres}"
PG_USER="${PG_USER:-casino}"
PG_DB="${PG_DB:-casino}"
API_SVC="${API_SVC:-api}"
WORKER_SVC="${WORKER_SVC:-worker}"
MINIO_SVC="${MINIO_SVC:-minio}"
REDIS_SVC="${REDIS_SVC:-redis}"
COMPOSE="${COMPOSE:-}"
KEY_FILE="${KEY_FILE:-$DIR/backup-key.txt}"
USE_PASSPHRASE=0
DO_DB=1
DO_OBJ=1
ASSUME_YES=0

while [ $# -gt 0 ]; do
  case "$1" in
    --key)            KEY_FILE="$2"; shift 2 ;;
    --key=*)          KEY_FILE="${1#*=}"; shift ;;
    --passphrase)     USE_PASSPHRASE=1; shift ;;
    --db-only)        DO_OBJ=0; shift ;;
    --objects-only)   DO_DB=0; shift ;;
    --yes|-y)         ASSUME_YES=1; shift ;;
    --compose)        COMPOSE="$2"; shift 2 ;;
    -h|--help)        sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

fail() { echo "ERROR: $*" >&2; exit 1; }
command -v docker >/dev/null 2>&1 || fail "docker is not on PATH"

if [ -z "$COMPOSE" ]; then
  for f in docker-compose.yml; do
    [ -f "$DIR/$f" ] && COMPOSE="$DIR/$f" && break
  done
fi

resolve_container() {
  local svc="$1" id=""
  if [ -n "$COMPOSE" ]; then
    id="$(docker compose -f "$COMPOSE" ps -q "$svc" 2>/dev/null | head -1 || true)"
  fi
  if [ -z "$id" ]; then
    id="$(docker ps --format '{{.ID}} {{.Names}}' 2>/dev/null | awk -v s="-$svc-" 'index($2, s) {print $1; exit}')"
  fi
  printf '%s' "$id"
}

TMP="$(mktemp -d)"
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT INT TERM

echo "=== 1/7 decrypt ==="
# Prefer the host's node. When there is none (a bare VPS), do the decryption in
# a throwaway container — with explicitly translated paths, because the file and
# the key have to be reachable at their mounted locations inside it.
NODE_HOST=0
if command -v node >/dev/null 2>&1; then NODE_HOST=1; fi

FILE_DIR="$(cd "$(dirname "$FILE")" && pwd)"
FILE_BASE="$(basename "$FILE")"
TAR="$TMP/platform.tar"

IN_ARG="$FILE"
OUT_ARG="$TAR"
KEY_ARG="$KEY_FILE"
if [ "$NODE_HOST" != "1" ]; then
  IN_ARG="/in/$FILE_BASE"
  OUT_ARG="/out/platform.tar"
  case "$KEY_FILE" in
    "$DIR"/*) KEY_ARG="/repo/${KEY_FILE#"$DIR"/}" ;;
    *) fail "the host has no node, so decryption runs in a container: put the private key inside the repo directory (e.g. $DIR/backup-key.txt) or install node" ;;
  esac
fi

run_crypto() {
  if [ "$NODE_HOST" = "1" ]; then
    node "$DIR/scripts/backup-crypto.mjs" "$@"
  else
    docker run --rm -v "$DIR:/repo:ro" -v "$FILE_DIR:/in:ro" -v "$TMP:/out" -w /repo \
      node:22-alpine node scripts/backup-crypto.mjs "$@"
  fi
}

if [ "$USE_PASSPHRASE" = "1" ]; then
  run_crypto decrypt --in "$IN_ARG" --out "$OUT_ARG"
else
  if [ ! -f "$KEY_FILE" ]; then
    fail "private key not found: $KEY_FILE
  Point at yours with --key PATH, or use --passphrase if the archive was made that way."
  fi
  run_crypto decrypt --key "$KEY_ARG" --in "$IN_ARG" --out "$OUT_ARG"
fi

tar xf "$TAR" -C "$TMP"
[ -f "$TMP/manifest.json" ] || fail "archive has no manifest.json — not a platform backup?"

echo "=== 2/7 verify ==="
verify_part() {  # $1 = relative path, $2 = expected sha
  [ -f "$TMP/$1" ] || fail "missing from archive: $1"
  actual="$(sha256sum "$TMP/$1" | cut -d' ' -f1)"
  [ "$actual" = "$2" ] || fail "CHECKSUM MISMATCH for $1
    expected $2
    actual   $actual
  The archive is corrupt or was modified. Restoring it could half-wipe the database, so this stops here."
  echo "  ok  $1  ($actual)"
}
# Read one field from manifest.json. python3 is the reliable default; node is
# the fallback. Both are read-only, and the manifest is generated by us.
mf() {  # $1 = python expression over `m`
  local expr="$1"
  if command -v python3 >/dev/null 2>&1; then
    python3 -c "
import json,sys
m=json.load(open(sys.argv[1]))
v=eval(sys.argv[2],{'m':m,'json':json})
print('True' if v is True else 'False' if v is False else v)
" "$TMP/manifest.json" "$expr"
  elif command -v node >/dev/null 2>&1; then
    node -e "
const m=require(process.argv[1]);
let v=eval(process.argv[2]);
console.log(v===true?'True':v===false?'False':String(v));
" "$TMP/manifest.json" "$expr"
  else
    echo "ERROR: restoring needs python3 or node to read the manifest" >&2
    exit 1
  fi
}

DB_SHA="$(mf "m['parts']['database.dump']['sha256']")"
[ -n "$DB_SHA" ] || fail "manifest is missing parts.database.dump.sha256"
verify_part "database.dump" "$DB_SHA"
if mf "'objects/minio-data.tar.gz' in m['parts']" 2>/dev/null | grep -q True; then
  OBJ_SHA="$(mf "m['parts']['objects/minio-data.tar.gz']['sha256']")"
  verify_part "objects/minio-data.tar.gz" "$OBJ_SHA"
  HAVE_OBJECTS=1
else
  HAVE_OBJECTS=0
  echo "  (archive contains no images)"
fi

echo "=== 3/7 report ==="
CREATED="$(mf "m.get('createdAt','?')")"
HOST="$(mf "m.get('host','?')")"
COMMIT="$(mf "m.get('appCommit','?')")"
KEY_FP="$(mf "m.get('encryption',{}).get('keyFingerprint','none')")"
echo "  created:  $CREATED  (from $HOST, commit $COMMIT)"
echo "  rows:     $(mf "', '.join(f\"{k}={v}\" for k,v in m['counts'].items())")"

PG_CT="$(resolve_container "$PG_SVC")"
[ -n "$PG_CT" ] || fail "no running '$PG_SVC' container — start the stack (docker compose up -d postgres redis minio) first"

API_CT="$(resolve_container "$API_SVC")"
TARGET_KEY=""
if [ -n "$API_CT" ]; then
  TARGET_KEY="$(docker exec "$API_CT" printenv ENCRYPTION_KEY 2>/dev/null || true)"
  [ -z "$TARGET_KEY" ] && TARGET_KEY="$(docker exec "$API_CT" printenv AES_ENCRYPTION_KEY 2>/dev/null || true)"
fi
TARGET_FP="none"
[ -n "$TARGET_KEY" ] && TARGET_FP="$(printf '%s' "$TARGET_KEY" | sha256sum | cut -c1-16)"

if [ "$KEY_FP" != "none" ] && [ "$TARGET_FP" != "none" ] && [ "$KEY_FP" != "$TARGET_FP" ]; then
  echo
  echo "  !! ENCRYPTION_KEY MISMATCH"
  echo "     backup was made with fingerprint $KEY_FP"
  echo "     this stack has              $TARGET_FP"
  echo "     Saved payout-account details (bank / mobile wallet) will be UNREADABLE"
  echo "     unless you set ENCRYPTION_KEY to the original value before starting the API."
  echo
elif [ "$KEY_FP" != "none" ]; then
  echo "  ENCRYPTION_KEY fingerprint matches ($KEY_FP)"
fi

echo "=== 4/7 confirm ==="
SCOPE=""
if [ "$DO_DB" = "1" ]; then SCOPE="database '$PG_DB'"; fi
if [ "$DO_OBJ" = "1" ] && [ "$HAVE_OBJECTS" = "1" ]; then
  if [ -n "$SCOPE" ]; then SCOPE="$SCOPE and the MinIO volume"; else SCOPE="the MinIO volume"; fi
fi
echo "  This will REPLACE the contents of ${SCOPE:-nothing (both parts skipped)}."
if [ "$ASSUME_YES" != "1" ]; then
  printf '  Type RESTORE to continue: '
  read -r CONFIRM
  [ "$CONFIRM" = "RESTORE" ] || { echo "aborted — nothing was changed."; exit 1; }
fi

if [ "$DO_DB" = "1" ]; then
  echo "=== 5/7 database ==="
  for svc in "$API_SVC" "$WORKER_SVC"; do
    ct="$(resolve_container "$svc")"
    [ -n "$ct" ] && { echo "  stopping $svc"; docker stop "$ct" >/dev/null; }
  done

  docker cp "$TMP/database.dump" "$PG_CT:/tmp/platform-restore.dump" >/dev/null
  # Prove it landed BEFORE we drop anything — a half-copied dump plus a
  # dropped database is the one unrecoverable state this script must never reach.
  docker exec "$PG_CT" test -s /tmp/platform-restore.dump \
    || fail "the dump did not land inside the container — nothing was dropped"
  echo "  dropping + recreating $PG_DB"
  docker exec "$PG_CT" dropdb -U "$PG_USER" --force --if-exists "$PG_DB"
  docker exec "$PG_CT" createdb -U "$PG_USER" -O "$PG_USER" "$PG_DB"

  echo "  restoring (silence = success)"
  docker exec "$PG_CT" pg_restore -U "$PG_USER" -d "$PG_DB" --no-owner --no-privileges \
    --exit-on-error /tmp/platform-restore.dump
  docker exec "$PG_CT" rm -f /tmp/platform-restore.dump || true

  echo "  verifying row counts against the manifest"
  MISMATCH=0
  for t in User Wallet GameRound Transaction Deposit Withdrawal AdminUser GameConfig; do
    EXPECTED="$(mf "m['counts'].get('$t')")"
    [ "$EXPECTED" = "None" ] && continue
    ACTUAL="$(docker exec "$PG_CT" psql -U "$PG_USER" -d "$PG_DB" -tAc "SELECT COUNT(*) FROM \"$t\";" | tr -d '[:space:]')"
    if [ "$ACTUAL" = "$EXPECTED" ]; then
      echo "    ok  $t = $ACTUAL"
    else
      echo "    MISMATCH $t: expected $EXPECTED, got $ACTUAL"
      MISMATCH=1
    fi
  done
  [ "$MISMATCH" = "0" ] || echo "  WARNING: some counts differ — inspect before going live" >&2
else
  echo "=== 5/7 database skipped (--objects-only) ==="
fi

if [ "$DO_OBJ" = "1" ] && [ "$HAVE_OBJECTS" = "1" ]; then
  echo "=== 6/7 images ==="
  MINIO_CT="$(resolve_container "$MINIO_SVC")"
  MINIO_VOL=""
  if [ -n "$MINIO_CT" ]; then
    MINIO_VOL="$(docker inspect -f '{{ range .Mounts }}{{ if eq .Destination "/data" }}{{ .Name }}{{ end }}{{ end }}' "$MINIO_CT" 2>/dev/null || true)"
    echo "  stopping $MINIO_SVC so it cannot hold files open mid-extract"
    docker stop "$MINIO_CT" >/dev/null
  fi
  [ -n "$MINIO_VOL" ] || MINIO_VOL="$(docker volume ls -q | grep -E '_minio_data$' | head -1)"
  [ -n "$MINIO_VOL" ] || fail "no MinIO volume found (create the stack first, or use --db-only)"
  echo "  extracting into $MINIO_VOL"
  docker run --rm -v "$MINIO_VOL":/data -v "$TMP/objects":/ro alpine \
    sh -c 'cd /data && tar xzf /ro/minio-data.tar.gz'
  [ -n "${MINIO_CT:-}" ] && { docker start "$MINIO_CT" >/dev/null; echo "  $MINIO_SVC restarted"; }
else
  echo "=== 6/7 images skipped ==="
fi

echo "=== 7/7 finish ==="
REDIS_CT="$(resolve_container "$REDIS_SVC")"
if [ -n "$REDIS_CT" ]; then
  echo "  flushing Redis caches (they describe the old rows)"
  docker exec "$REDIS_CT" redis-cli FLUSHDB >/dev/null 2>&1 || \
    echo "  (redis is password-protected — run: docker exec $REDIS_CT redis-cli -a <pw> FLUSHDB)" >&2
fi

for svc in "$API_SVC" "$WORKER_SVC"; do
  ct="$(resolve_container "$svc")"
  [ -n "$ct" ] && { echo "  starting $svc"; docker start "$ct" >/dev/null; }
done

echo
echo "  Restore complete. Verify:"
echo "    docker logs --tail=30 $(resolve_container "$API_SVC" 2>/dev/null || echo '<api>')"
echo "    -> expect 'database already seeded (N games) — skipping seed'"
echo "    then log in and confirm a deposit proof image opens."
